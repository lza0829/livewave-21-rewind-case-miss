"""水位变小写闸（全局唯一口径：未结案件封锁）。

架构甲：变小写是「处置」——
- 处置成功必须同票落一笔回退案件（房间、旧水位、请求值、处置态、案件号、前案号），
  并在同一事务内降水位 + 重开窗止高于新水位的已关闭窗（关闭集合必须跟上水位）。
- 同房存在未结案件时，新的变小写**整票拒绝**，只能先结案；半截失败整票回滚。
- 抬升写仍在同事务内推进水位并关窗；入流装载统一经 `守卫写水位`，永不许变小。
并发下由 BEGIN IMMEDIATE 串行化，杜绝「水位已动而关闭集合未跟」。
"""
from app.db import 连接
from app.seed import 此刻
from app.services import 时间, 热度窗
from app.modules import 回退案件

口径 = "未结案件封锁"
_封锁理由 = "存在未结回退案件，须先结案再处置（未结案件封锁）"


class 水位回退拒绝(Exception):
    """装载等内部写路径试图把水位写小时抛出。变小只能走处置闸（立案同票）。"""

    def __init__(self, 结果: dict):
        super().__init__(结果.get("理由") or "入流水位只进不退")
        self.结果 = 结果


def _房(conn, 房间键: str):
    return conn.execute("SELECT * FROM 直播间 WHERE 房间键=?", (房间键,)).fetchone()


def _水位(conn, 房间键: str):
    return conn.execute("SELECT * FROM 水位线 WHERE 房间键=?", (房间键,)).fetchone()


def _旧值(房, 水位) -> str:
    return 水位["事件时水位"] if 水位 else 房["开播事件时"]


def _受影响窗(conn, 房间键: str, 新值: str, 允许迟到: int) -> list:
    """若处置降到此新值，需要同票重开的已关闭窗（窗止高于新水位）。"""
    rows = conn.execute(
        """SELECT * FROM 热度窗
           WHERE 房间键=? AND 状态='已关闭' AND 窗止事件时>?
           ORDER BY 窗起事件时""",
        (房间键, 新值),
    ).fetchall()
    return [
        {
            "窗键": r["窗键"],
            "窗起事件时": r["窗起事件时"],
            "窗止事件时": r["窗止事件时"],
            "当前状态": r["状态"],
            "旁路界": 时间.加秒(r["窗止事件时"], 允许迟到),
            "若重开则": "开启",
        }
        for r in rows
    ]


def _组装(conn, 房间键: str, 新值: str) -> dict:
    """只读裁决：不写任何表。valid=False ⇔ 该请求被拒绝。"""
    房 = _房(conn, 房间键)
    if not 房:
        return {
            "房间键": 房间键,
            "旧值": None,
            "新值": 新值,
            "valid": False,
            "口径": 口径,
            "裁决": "拒绝",
            "理由": "未知直播间",
            "水位提交后": None,
            "拒绝列表": [{"房间键": 房间键, "旧值": None, "新值": 新值, "理由": "未知直播间"}],
            "重开列表": [],
            "受影响窗": [],
        }

    水位 = _水位(conn, 房间键)
    旧值 = _旧值(房, 水位)
    允许迟到 = int(水位["允许迟到秒"]) if 水位 else 30
    变小 = 时间.解析(新值) < 时间.解析(旧值)

    if 变小:
        未结 = 回退案件.未结案(conn, 房间键)
        if 未结:
            理由 = f"{_封锁理由}：{未结['案件号']}"
            return {
                "房间键": 房间键,
                "旧值": 旧值,
                "新值": 新值,
                "valid": False,
                "口径": 口径,
                "裁决": "拒绝",
                "理由": 理由,
                "水位提交后": 旧值,
                "未结案件号": 未结["案件号"],
                "拒绝列表": [
                    {"房间键": 房间键, "旧值": 旧值, "新值": 新值, "理由": 理由}
                ],
                "重开列表": [],
                "受影响窗": _受影响窗(conn, 房间键, 新值, 允许迟到),
            }
        return {
            "房间键": 房间键,
            "旧值": 旧值,
            "新值": 新值,
            "valid": True,
            "口径": 口径,
            "裁决": "允许",
            "理由": "受控变小：同票立案、降水位并重开越界窗",
            "水位提交后": 新值,
            "拒绝列表": [],
            "重开列表": _受影响窗(conn, 房间键, 新值, 允许迟到),
            "受影响窗": _受影响窗(conn, 房间键, 新值, 允许迟到),
        }

    return {
        "房间键": 房间键,
        "旧值": 旧值,
        "新值": 新值,
        "valid": True,
        "口径": 口径,
        "裁决": "允许",
        "理由": "新值不低于旧值，水位可抬升",
        "水位提交后": 新值,
        "拒绝列表": [],
        "重开列表": [],
        "受影响窗": [],
    }


def 审查(房间键: str, 新值: str) -> dict:
    """水位变小只读接口：房间、旧值、新值、拒绝/重开列表、valid。

    不开启事务、不写库；并发下读到的是某一一致快照。
    """
    conn = 连接()
    try:
        return _组装(conn, 房间键, 新值)
    finally:
        conn.close()


def 提交(房间键: str, 新值: str, 处理时: str | None = None) -> dict:
    """水位写闸。拒绝或半截失败时整票回滚，水位、案件簿与窗态一个字节不变。"""
    处理时 = 处理时 or 此刻()
    conn = 连接()
    try:
        conn.execute("BEGIN IMMEDIATE")
        try:
            结果 = _组装(conn, 房间键, 新值)
            结果["已落盘"] = False
            结果["新关窗"] = 0
            结果["案件号"] = ""
            结果["处置态"] = ""
            if not 结果["valid"]:
                conn.rollback()
                当前 = _水位(conn, 房间键) if _房(conn, 房间键) else None
                结果["当前水位"] = 当前["事件时水位"] if 当前 else None
                return 结果

            旧值 = 结果["旧值"]
            水位行 = _水位(conn, 房间键)
            允许迟到 = int(水位行["允许迟到秒"]) if 水位行 else 30
            if 时间.解析(新值) > 时间.解析(旧值):
                守卫写水位(conn, 房间键, 新值, 处理时)
                规行 = conn.execute("SELECT 值 FROM 站规 WHERE 键='窗长秒'").fetchone()
                窗长 = int(规行["值"]) if 规行 else 60
                结果["新关窗"] = 热度窗.尝试关窗(
                    conn, 房间键, 新值, 允许迟到, 窗长, 处理时
                )
            elif 时间.解析(新值) < 时间.解析(旧值):
                # 受控变小处置：同票立案 → 降水位 → 重开越界窗；任一失败整票回滚。
                案 = 回退案件.立案(conn, 房间键, 旧值, 新值, 处理时)
                if 水位行:
                    conn.execute(
                        "UPDATE 水位线 SET 事件时水位=?, 更新处理时=? WHERE 房间键=?",
                        (新值, 处理时, 房间键),
                    )
                else:
                    conn.execute(
                        "INSERT INTO 水位线(房间键, 事件时水位, 允许迟到秒, 更新处理时) VALUES (?,?,?,?)",
                        (房间键, 新值, 允许迟到, 处理时),
                    )
                重开 = 热度窗.重开越界窗(conn, 房间键, 新值, 处理时)
                结果["案件号"] = 案["案件号"]
                结果["前案案件号"] = 案["前案案件号"]
                结果["处置态"] = 案["处置态"]
                结果["重开列表"] = 重开
                结果["水位提交后"] = 新值
            conn.commit()
            结果["已落盘"] = True
            结果["当前水位"] = _读水位值(conn, 房间键)
            return 结果
        except Exception:
            conn.rollback()
            raise
    finally:
        conn.close()


def _读水位值(conn, 房间键: str):
    行 = _水位(conn, 房间键)
    return 行["事件时水位"] if 行 else None


def 守卫写水位(conn, 房间键: str, 新值: str, 处理时: str, 允许迟到秒: int = 30) -> str:
    """入流事务内水位写入的唯一入口：变小即抛异常，禁止绕道 UPDATE。

    变小只能走 `提交` 处置闸（同票立案）。调用方须已处于 BEGIN IMMEDIATE 事务中。
    """
    行 = _水位(conn, 房间键)
    当前 = 行["事件时水位"] if 行 else None
    if 当前 is not None and 时间.解析(新值) < 时间.解析(当前):
        raise 水位回退拒绝(
            {
                "房间键": 房间键,
                "旧值": 当前,
                "新值": 新值,
                "valid": False,
                "口径": 口径,
                "裁决": "拒绝",
                "理由": "入流水位只进不退；变小须走处置闸立案",
                "水位提交后": 当前,
                "拒绝列表": [
                    {"房间键": 房间键, "旧值": 当前, "新值": 新值, "理由": "入流水位只进不退"}
                ],
                "重开列表": [],
            }
        )
    if 当前 is None:
        conn.execute(
            "INSERT INTO 水位线(房间键, 事件时水位, 允许迟到秒, 更新处理时) VALUES (?,?,?,?)",
            (房间键, 新值, 允许迟到秒, 处理时),
        )
    elif 时间.解析(新值) > 时间.解析(当前):
        conn.execute(
            "UPDATE 水位线 SET 事件时水位=?, 更新处理时=? WHERE 房间键=?",
            (新值, 处理时, 房间键),
        )
    return 新值


def 不变式(conn, 房间键: str | None = None) -> list:
    """窗-水位互证不变式（两种口径下都必须成立）。

    - 水位 >= 窗止 的窗不得仍处于开启（关窗表必须跟上水位）。
    - 已关闭窗的窗止不得高于当前水位（否则水位被回退而关闭集合未跟）。
    """
    问题 = []
    房滤 = " WHERE w.房间键=?" if 房间键 else ""
    参 = (房间键,) if 房间键 else ()
    for 行 in conn.execute(
        f"SELECT w.房间键, w.事件时水位 FROM 水位线 w{房滤}", 参
    ).fetchall():
        房间键, 水位 = 行["房间键"], 行["事件时水位"]
        未关 = conn.execute(
            """SELECT 窗键 FROM 热度窗
               WHERE 房间键=? AND 状态='开启' AND 窗止事件时<=?
               ORDER BY 窗起事件时""",
            (房间键, 水位),
        ).fetchall()
        if 未关:
            问题.append(
                f"水位已过窗止但窗未关:{房间键} 水位{水位} 开启窗{','.join(r['窗键'] for r in 未关)}"
            )
        越界关 = conn.execute(
            """SELECT 窗键 FROM 热度窗
               WHERE 房间键=? AND 状态='已关闭' AND 窗止事件时>?
               ORDER BY 窗起事件时""",
            (房间键, 水位),
        ).fetchall()
        if 越界关:
            问题.append(
                f"已关闭窗窗止高于水位:{房间键} 水位{水位} 窗{','.join(r['窗键'] for r in 越界关)}"
            )
    return 问题
